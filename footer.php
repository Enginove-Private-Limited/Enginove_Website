<script>

document.addEventListener(
    "DOMContentLoaded",
    function () {

        const form =
            document.getElementById("newsletterForm");

        const button =
            document.getElementById("newsletterButton");

        const message =
            document.getElementById("newsletterMessage");


        if (!form) {
            return;
        }


        form.addEventListener(
            "submit",
            async function (event) {

                event.preventDefault();


                message.className =
                    "newsletter-message";

                message.textContent =
                    "";


                const originalButton =
                    button.innerHTML;


                button.disabled = true;

                button.innerHTML =
                    'SUBSCRIBING... <i class="bi bi-hourglass-split"></i>';


                try {

                    const response =
                        await fetch(
                            form.action,
                            {
                                method: "POST",
                                body: new FormData(form),
                                headers: {
                                    "Accept":
                                        "application/json"
                                }
                            }
                        );


                    const text =
                        await response.text();


                    let data;


                    try {

                        data =
                            JSON.parse(text);

                    } catch (jsonError) {

                        throw new Error(
                            "Invalid server response."
                        );

                    }


                    if (data.success) {

                        message.className =
                            "newsletter-message success";

                        message.textContent =
                            data.message ||
                            "Thank you for subscribing to Enginove News & Updates.";

                        form.reset();

                    } else {

                        message.className =
                            "newsletter-message error";

                        message.textContent =
                            data.message ||
                            "Unable to subscribe. Please try again.";

                    }


                } catch (error) {

                    message.className =
                        "newsletter-message error";

                    message.textContent =
                        "Unable to connect to the newsletter service. Please try again.";

                }


                button.disabled = false;

                button.innerHTML =
                    originalButton;

            }
        );

    }
);

</script>
