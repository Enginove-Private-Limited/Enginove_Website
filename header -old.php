<script>

document.addEventListener(
  "DOMContentLoaded",
  function () {


    const hamburgerBtn =
      document.getElementById(
        "hamburgerBtn"
      );


    const closeDrawer =
      document.getElementById(
        "closeDrawer"
      );


    const mobileDrawer =
      document.getElementById(
        "mobileDrawer"
      );


    const mobileOverlay =
      document.getElementById(
        "mobileOverlay"
      );



    /* =========================================
       OPEN DRAWER
    ========================================= */

    if (hamburgerBtn) {

      hamburgerBtn.addEventListener(
        "click",
        function () {

          mobileDrawer.classList.add(
            "active"
          );

          mobileOverlay.classList.add(
            "active"
          );

          document.body.style.overflow =
            "hidden";

        }
      );

    }



    /* =========================================
       CLOSE DRAWER
    ========================================= */

    function closeMobileDrawer() {

      mobileDrawer.classList.remove(
        "active"
      );

      mobileOverlay.classList.remove(
        "active"
      );

      document.body.style.overflow = "";

    }


    if (closeDrawer) {

      closeDrawer.addEventListener(
        "click",
        closeMobileDrawer
      );

    }


    if (mobileOverlay) {

      mobileOverlay.addEventListener(
        "click",
        closeMobileDrawer
      );

    }



    /* =========================================
       MOBILE DROPDOWNS
    ========================================= */

    const dropdownButtons =
      document.querySelectorAll(
        ".mobile-dropdown-btn"
      );


    dropdownButtons.forEach(
      function (button) {

        button.addEventListener(
          "click",
          function () {

            const submenu =
              this.nextElementSibling;


            this.classList.toggle(
              "active"
            );


            submenu.classList.toggle(
              "active"
            );

          }
        );

      }
    );



    /* =========================================
       CLOSE WHEN LINK IS CLICKED
    ========================================= */

    const mobileLinks =
      document.querySelectorAll(
        ".mobile-menu > a, .mobile-submenu a"
      );


    mobileLinks.forEach(
      function (link) {

        link.addEventListener(
          "click",
          function () {

            closeMobileDrawer();

          }
        );

      }
    );



    /* =========================================
       ESCAPE KEY
    ========================================= */

    document.addEventListener(
      "keydown",
      function (event) {

        if (
          event.key === "Escape"
        ) {

          closeMobileDrawer();

        }

      }
    );


  }
);

</script>